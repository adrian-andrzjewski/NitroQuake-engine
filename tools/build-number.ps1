# Build identity state is shared by Git worktrees, outside tracked sources.
function Get-NitroQuakeBuildStateDirectory {
    param([Parameter(Mandatory)][string]$RepoRoot)
    $git = Get-Command git -ErrorAction SilentlyContinue
    if ($null -ne $git) {
        $common = & $git.Source -C $RepoRoot rev-parse --path-format=absolute --git-common-dir 2>$null
        if ($LASTEXITCODE -eq 0 -and $common) {
            return [IO.Path]::GetFullPath([string]$common)
        }
    }
    # Source archives also support automatic numbering, without Git installed.
    return Join-Path $RepoRoot 'out'
}

function Get-NextNitroQuakeBuildNumber {
    param([Parameter(Mandatory)][string]$StateDirectory)
    [IO.Directory]::CreateDirectory($StateDirectory) | Out-Null
    $counterPath = Join-Path $StateDirectory 'nitroquake-build-number'
    $lockPath = $counterPath + '.lock'
    $lock = $null
    $deadline = [DateTime]::UtcNow.AddSeconds(30)
    while ($null -eq $lock) {
        try {
            $lock = [IO.File]::Open($lockPath, [IO.FileMode]::OpenOrCreate,
                [IO.FileAccess]::ReadWrite, [IO.FileShare]::None)
        } catch [IO.IOException] {
            if ([DateTime]::UtcNow -ge $deadline) { throw "Timed out reserving a NitroQuake build number: $lockPath" }
            Start-Sleep -Milliseconds 50
        }
    }
    $temporary = $counterPath + '.' + [Guid]::NewGuid().ToString('N') + '.tmp'
    try {
        [long]$previous = 0
        if ([IO.File]::Exists($counterPath)) {
            $text = [IO.File]::ReadAllText($counterPath).Trim()
            if ($text -notmatch '^[0-9]+$' -or
                -not [long]::TryParse($text, [ref]$previous) -or $previous -ge [int]::MaxValue) {
                throw "Invalid or exhausted NitroQuake build counter: $counterPath"
            }
        }
        $next = $previous + 1
        # Replace atomically while holding a separate, OS-owned lock. A failed
        # build can leave a gap; no later build reuses its reserved identity.
        [IO.File]::WriteAllText($temporary, $next.ToString([Globalization.CultureInfo]::InvariantCulture),
            [Text.Encoding]::ASCII)
        [IO.File]::Move($temporary, $counterPath, $true)
        return $next
    } finally {
        if ([IO.File]::Exists($temporary)) { [IO.File]::Delete($temporary) }
        $lock.Dispose()
    }
}

function New-NitroQuakeBuildIdentity {
    param([Parameter(Mandatory)][string]$RepoRoot,
          [Parameter(Mandatory)][string]$HeaderPath)
    $state = Get-NitroQuakeBuildStateDirectory -RepoRoot $RepoRoot
    $number = Get-NextNitroQuakeBuildNumber -StateDirectory $state
    $header = "/* Generated by build-dos.ps1; do not edit. */`n#define NITROQUAKE_BUILD_NUMBER $number`n"
    [IO.File]::WriteAllText($HeaderPath, $header, [Text.Encoding]::ASCII)
    return [pscustomobject]@{ number = $number; version = "NitroQuake v0.999+$number" }
}
